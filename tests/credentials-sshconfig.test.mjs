// `ssh -G` prints the configuration ssh would use and connects to nothing.
// Always with -F: ssh finds its default config through the real passwd home,
// whatever HOME says, and a test must never read or depend on that.
import assert from 'node:assert/strict';
import test from 'node:test';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { spawnSync } from 'node:child_process';
import { sshConfigText, ensureInclude, hasInclude } from '../docker/setup/credentials/sshconfig.mjs';

const keyed = { id: 'build-server', type: 'ssh', fields: { host: '192.0.2.10', port: 2222, username: 'deploy', auth: 'key', publicKey: 'ssh-ed25519 AAAAfixture' } };
const password = { id: 'old-box', type: 'ssh', fields: { host: 'old.example.test', port: 22, username: 'root', auth: 'password' } };
const token = { id: 'project-api', type: 'token', fields: { host: 'not-a-server.example.test' } };
async function folder(t, prefix = 't3-vault-sshconfig-') {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), prefix));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  return root;
}
/** What ssh itself would use for this name, connecting to nothing. */
const resolved = (file, name) => {
  const answer = spawnSync('/usr/bin/ssh', ['-G', '-F', file, name], { encoding: 'utf8', timeout: 10000 });
  assert.equal(answer.status, 0, answer.stderr);
  const options = new Map();
  for (const line of answer.stdout.split('\n')) {
    const at = line.indexOf(' ');
    if (at < 1) continue;
    const key = line.slice(0, at);
    options.set(key, [...(options.get(key) || []), line.slice(at + 1)]);
  }
  return key => options.get(key)?.at(-1);
};
const written = async (root, credentials, name = 'ssh_config') => { const file = path.join(root, name); await fs.writeFile(file, sshConfigText(credentials, { root }), { mode: 0o600 }); return file; };

test('the generated file has a block for each SSH credential, in order, and nothing else', () => {
  const text = sshConfigText([password, token, keyed], { root: '/fixture/vault' });
  assert.match(text, /^# Generated by t3-vault\. Changes here are replaced\./);
  assert.deepEqual(text.match(/^Host .*$/gm), ['Host build-server', 'Host old-box']);
  assert.doesNotMatch(text, /project-api|not-a-server/);
  assert.match(text, /^  HostName 192\.0\.2\.10$/m); assert.match(text, /^  Port 2222$/m); assert.match(text, /^  User deploy$/m);
  assert.match(text, /^  IdentityFile "\/fixture\/vault\/keys\/build-server"$/m);
  assert.match(text, /^  UserKnownHostsFile "\/fixture\/vault\/known_hosts\/build-server"$/m);
  assert.match(text, /^  GlobalKnownHostsFile \/dev\/null$/m);
  assert.match(text, /^  StrictHostKeyChecking yes$/m);
  assert.match(text, /^  LocalCommand \/usr\/bin\/touch "\/fixture\/vault\/usage\/build-server\.touch" 2>\/dev\/null$/m);
  assert.doesNotMatch(text, /ssh-ed25519|AAAA/, 'a public key is not needed here, and a private one never is');
  assert.equal(text.endsWith('\n'), true);
  assert.equal(sshConfigText([], { root: '/fixture/vault' }).includes('Host '), false);
  assert.equal(sshConfigText([token], { root: '/fixture/vault' }), sshConfigText([], { root: '/fixture/vault' }));
});

test('ssh itself resolves a key credential to the saved server, key and pinned host', async t => {
  const root = await folder(t), get = resolved(await written(root, [keyed, password]), 'build-server');
  assert.equal(get('hostname'), '192.0.2.10');
  assert.equal(get('port'), '2222');
  assert.equal(get('user'), 'deploy');
  assert.equal(get('identityfile'), path.join(root, 'keys', 'build-server'));
  assert.equal(get('identitiesonly'), 'yes');
  assert.equal(get('batchmode'), 'yes');
  assert.equal(get('hostkeyalias'), 'build-server');
  assert.equal(get('stricthostkeychecking'), 'true');
  assert.equal(get('userknownhostsfile'), path.join(root, 'known_hosts', 'build-server'));
  assert.equal(get('globalknownhostsfile'), '/dev/null');
  assert.equal(get('preferredauthentications'), 'publickey');
  assert.equal(get('permitlocalcommand'), 'yes');
  assert.match(get('localcommand'), /usage\/build-server\.touch/);
});

test('ssh itself resolves a password credential without offering any key', async t => {
  const root = await folder(t), get = resolved(await written(root, [keyed, password]), 'old-box');
  assert.equal(get('hostname'), 'old.example.test');
  assert.equal(get('port'), '22');
  assert.equal(get('user'), 'root');
  assert.match(get('pubkeyauthentication'), /^(?:no|false)$/, 'OpenSSH versions print this either way');
  assert.equal(get('preferredauthentications'), 'password,keyboard-interactive');
  assert.equal(get('hostkeyalias'), 'old-box');
  assert.equal(get('stricthostkeychecking'), 'true');
  assert.equal(get('userknownhostsfile'), path.join(root, 'known_hosts', 'old-box'));
  assert.notEqual(get('identityfile'), path.join(root, 'keys', 'old-box'));
});

test('a name that isn\'t saved gets none of it', async t => {
  const root = await folder(t), get = resolved(await written(root, [keyed]), 'somewhere-else');
  assert.equal(get('hostname'), 'somewhere-else');
  assert.notEqual(get('user'), 'deploy');
  assert.equal(get('hostkeyalias'), undefined);
  assert.notEqual(get('stricthostkeychecking'), 'true');
});

test('a home with spaces or quotes in its path still resolves', async t => {
  const root = path.join(await folder(t), 'with "quotes" and spaces'); await fs.mkdir(root);
  const get = resolved(await written(root, [keyed]), 'build-server');
  assert.equal(get('identityfile'), path.join(root, 'keys', 'build-server'));
  assert.equal(get('userknownhostsfile'), path.join(root, 'known_hosts', 'build-server'));
  assert.equal(get('hostname'), '192.0.2.10');
});

test('a % in the path is taken literally, not as one of ssh\'s own tokens', async t => {
  const root = path.join(await folder(t), '100%done'); await fs.mkdir(root);
  const file = await written(root, [keyed]), get = resolved(file, 'build-server');
  assert.equal(get('userknownhostsfile'), path.join(root, 'known_hosts', 'build-server'), '%d would otherwise become the home folder');
  assert.ok(get('identityfile').endsWith('/100%%done/keys/build-server'), 'expanded when ssh loads it, so -G shows it doubled');
  assert.ok(get('localcommand').includes('100%%done/usage/build-server.touch'));
});

test('IPv6 servers work', async t => {
  const root = await folder(t);
  const get = resolved(await written(root, [{ ...keyed, fields: { ...keyed.fields, host: '2001:db8::1' } }]), 'build-server');
  assert.equal(get('hostname'), '2001:db8::1');
});

test('the Include goes at the top of ~/.ssh/config, in front of what is there, and keeps its mode', async t => {
  const home = await folder(t), file = '/fixture/vault/ssh_config', target = path.join(home, '.ssh/config');
  await fs.mkdir(path.join(home, '.ssh'), { mode: 0o700 });
  const mine = 'Host *\n  ForwardAgent no\n\nHost mine\n  User me\n';
  await fs.writeFile(target, mine); await fs.chmod(target, 0o640);
  assert.equal(await hasInclude({ home, file }), false);
  assert.equal(await ensureInclude({ home, file }), true);
  assert.equal(await fs.readFile(target, 'utf8'), `Include "${file}"\n\n` + mine);
  assert.equal((await fs.stat(target)).mode & 0o777, 0o640);
  assert.equal(await hasInclude({ home, file }), true);
  assert.deepEqual((await fs.readdir(path.join(home, '.ssh'))).sort(), ['config'], 'no temporary file is left');
});

test('an Include that\'s already there isn\'t added again or moved', async t => {
  const home = await folder(t), file = '/fixture/vault/ssh_config', target = path.join(home, '.ssh/config');
  assert.equal(await ensureInclude({ home, file }), true);
  const once = await fs.readFile(target, 'utf8'), when = (await fs.stat(target)).mtimeMs;
  assert.equal(await ensureInclude({ home, file }), true);
  assert.equal(await fs.readFile(target, 'utf8'), once);
  assert.equal((await fs.stat(target)).mtimeMs, when, 'not even rewritten');
  const moved = `Host mine\n  User me\n\n  Include "${file}"\n`;
  await fs.writeFile(target, moved);
  assert.equal(await ensureInclude({ home, file }), true);
  assert.equal(await fs.readFile(target, 'utf8'), moved, 'somewhere else in the file still counts');
  assert.equal(await hasInclude({ home, file }), true);
  assert.equal(await hasInclude({ home, file: '/fixture/other/ssh_config' }), false);
});

test('it creates ~/.ssh at 700 and the config at 600 when neither exists', async t => {
  const home = await folder(t), file = '/fixture/vault/ssh_config';
  assert.equal(await hasInclude({ home, file }), false, 'nothing there is not an error');
  assert.equal(await ensureInclude({ home, file }), true);
  assert.equal((await fs.stat(path.join(home, '.ssh'))).mode & 0o777, 0o700);
  assert.equal((await fs.stat(path.join(home, '.ssh/config'))).mode & 0o777, 0o600);
  assert.equal(await fs.readFile(path.join(home, '.ssh/config'), 'utf8'), `Include "${file}"\n\n`);
});

test('an existing ~/.ssh keeps its own mode', async t => {
  const home = await folder(t);
  await fs.mkdir(path.join(home, '.ssh'), { mode: 0o755 }); await fs.chmod(path.join(home, '.ssh'), 0o755);
  assert.equal(await ensureInclude({ home, file: '/fixture/vault/ssh_config' }), true);
  assert.equal((await fs.stat(path.join(home, '.ssh'))).mode & 0o777, 0o755);
});

test('it refuses a config that is a link, without touching what the link points at', async t => {
  const home = await folder(t), file = '/fixture/vault/ssh_config', target = path.join(home, '.ssh/config'), outside = path.join(home, 'dotfiles-config');
  await fs.mkdir(path.join(home, '.ssh'), { mode: 0o700 }); await fs.writeFile(outside, 'Host mine\n'); await fs.symlink(outside, target);
  assert.equal(await ensureInclude({ home, file }), false);
  assert.equal(await fs.readFile(outside, 'utf8'), 'Host mine\n');
  assert.equal((await fs.lstat(target)).isSymbolicLink(), true);
  assert.deepEqual((await fs.readdir(path.join(home, '.ssh'))).sort(), ['config']);
  // Someone can add the line through the link themselves, and that counts.
  await fs.writeFile(outside, `Include "${file}"\n`);
  assert.equal(await hasInclude({ home, file }), true);
});

test('it refuses a config that is a folder, and any other failure comes back as false', async t => {
  const home = await folder(t), file = '/fixture/vault/ssh_config';
  await fs.mkdir(path.join(home, '.ssh/config'), { recursive: true });
  assert.equal(await ensureInclude({ home, file }), false);
  assert.equal(await hasInclude({ home, file }), false);
  const blocked = await folder(t); await fs.writeFile(path.join(blocked, '.ssh'), 'a file where a folder should be');
  assert.equal(await ensureInclude({ home: blocked, file }), false);
  const failing = await folder(t);
  assert.equal(await ensureInclude({ home: failing, file, effects: { ...fs, rename: async () => { throw new Error('injected failure'); } } }), false);
  assert.deepEqual(await fs.readdir(path.join(failing, '.ssh')), [], 'the temporary file is cleaned up');
});

test('ssh reads the generated file through the Include, ahead of a Host * block', async t => {
  const home = await folder(t), root = path.join(home, '.t3/server-credentials'); await fs.mkdir(root, { recursive: true });
  const file = await written(root, [keyed]), target = path.join(home, '.ssh/config');
  await fs.mkdir(path.join(home, '.ssh'), { mode: 0o700 });
  await fs.writeFile(target, 'Host *\n  User someone-else\n  Port 9999\n', { mode: 0o600 });
  assert.equal(await ensureInclude({ home, file }), true);
  const get = resolved(target, 'build-server');
  assert.equal(get('hostname'), '192.0.2.10'); assert.equal(get('user'), 'deploy'); assert.equal(get('port'), '2222');
  assert.equal(resolved(target, 'unrelated')('user'), 'someone-else', 'everything else still works as it did');
});
